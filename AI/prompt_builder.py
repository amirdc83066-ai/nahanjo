# کتابخانه‌های ساخت و پردازش پرامپت

import pandas as pd
import json
import numpy as np

# ساخت پرامپت تحلیل هوشمند برای AI

def build_ai_prompt(selected_column: str, dataframe, analysis) -> str:
    
    # استخراج داده کامل برای تحلیل زمینه‌ای
    
    full_dataset_csv = dataframe.to_csv(index=False)
    
    # آماده‌سازی ستون هدف
    
    column_series = dataframe[selected_column]
    column_series = pd.to_numeric(column_series, errors="coerce").dropna()
    values = column_series.tolist()

    column_df = pd.DataFrame({selected_column: values})
    data_text = column_df.to_csv(index=False)

    # محاسبه اطلاعات آماری ستون
    
    total_count = int(column_series.count())
    mean_value = float(column_series.mean())
    median_value = float(column_series.median())
    std_value = float(column_series.std())
    min_value = float(column_series.min())
    max_value = float(column_series.max())
    q1 = float(column_series.quantile(0.25))
    q3 = float(column_series.quantile(0.75))
    iqr = float(q3 - q1)
    skewness = float(column_series.skew())

    # آماده‌سازی خروجی تحلیل ناهنجاری
    
    try:
        clean_analysis = json.dumps(
            analysis,
            ensure_ascii=False,
            indent=2,
            default=float
        )
    except:
        clean_analysis = str(analysis)

    prompt = f"""
# 🎯 SYSTEM ROLE

شما یک متخصص ارشد استراتژی داده و تحلیل‌گر ارشد کسب‌وکار (Business Intelligence) هستید. 

وظیفه شما این است که نتایج به‌دست‌آمده از تحلیل‌های آماری و الگوریتمی (شامل Isolation Forest) را که توسط نرم‌افزار ما انجام شده، دریافت کرده و یک تحلیل سطح بالا، هوشمند و مدیریتی ارائه دهید.

تمرکز شما بر **تفسیر نتایج در بستر کل فایل**، **یافتن الگوهای پنهان** و **ارائه راهکارهای عملیاتی** است.

پاسخ شما باید:
- کاملاً فارسی، حرفه‌ای و در سطح گزارش‌های سازمانی باشد.
- فاقد هرگونه کد پایتون، جداول متنی یا Markdown فنی باشد.
- عمیق، علمی و با نگاهی به "علت رخداد" و "اثر بر بیزنس" نوشته شود.

------------------------------------------------------------

# 🌍 GLOBAL DATASET CONTEXT (FULL FILE ANALYSIS)

کل فایل داده جهت درک زمینه (Context) در اختیار شماست:

{full_dataset_csv}

شما موظف هستید:
1. ماهیت کلی فایل را شناسایی کنید (مالی، صنعتی، فروش، سنسور و...).
2. ناهنجاری‌های ستون هدف را با رفتار سایر ستون‌ها در کل فایل مقایسه کنید.
3. الگوهای تکرارشونده یا چرخه‌ای را در کل مجموعه داده کشف کنید.

------------------------------------------------------------

# 📌 TARGET COLUMN INFORMATION

نام ستون هدف: {selected_column}
تعداد داده‌ها: {total_count}

------------------------------------------------------------

# 📊 STATISTICAL PROFILE & PRELIMINARY ANALYSIS

نتایج زیر مستقیماً توسط محاسبات دقیق برنامه و الگوریتم Isolation Forest تولید شده است:

آمار توصیفی:
Mean: {mean_value} | Median: {median_value} | Std: {std_value}
Min: {min_value} | Max: {max_value}
Q1: {q1} | Q3: {q3} | IQR: {iqr} | Skewness: {skewness}

نتایج ناهنجاری‌های شناسایی شده (خروجی برنامه):
{clean_analysis}

------------------------------------------------------------

# 🧠 MISSION: INTELLIGENT INTERPRETATION

شما نباید مجدداً مدل Isolation Forest را اجرا کنید؛ بلکه باید نتایجی که برنامه در بخش "PRELIMINARY ANALYSIS" به شما داده را تفسیر کنید.

وظایف اصلی شما:
✅ تحلیل هوشمند نتایج: چرا الگوریتم Isolation Forest یا روش‌های آماری این نقاط را ناهنجار دانسته‌اند؟
✅ مرتبط‌سازی: آیا این ناهنجاری‌ها با مقادیر خاصی در ستون‌های دیگر فایل همبستگی دارند؟
✅ بررسی الگوها: آیا ناهنجاری‌ها به صورت خوشه‌ای (Cluster) ظاهر شده‌اند یا کاملاً تصادفی هستند؟
✅ ارائه پیشنهادهای مدیریتی: بر اساس این ناهنجاری‌ها، مدیران سیستم چه اقدامی باید انجام دهند؟

------------------------------------------------------------

# 📘 RESPONSE STRUCTURE

پاسخ دقیقاً شامل این بخش‌ها باشد:

1️⃣ مقدمه تحلیلی 🧬
- توضیح کوتاه در مورد اهمیت نظارت بر ناهنجاری‌ها در این نوع دیتاست خاص.
- اشاره به ترکیب قدرت آمار و الگوریتم ایزوله‌سازی برای دقت در نتایج.

2️⃣ تحلیل بستر داده (Contextual Analysis) 🌐
- تحلیل کل فایل و شناسایی ماهیت سیستم.
- بررسی ارتباط ستون هدف با سایر بخش‌های فایل داده.
- یافتن روندهای کلی و رفتارهای چرخه‌ای در کل مجموعه.

3️⃣ تفسیر تخصصی ناهنجاری‌های شناسایی شده 🔍
- تحلیل دقیق مواردی که برنامه به عنوان ناهنجاری (مخصوصاً با نماد ایزوله‌سازی 🌲) گزارش کرده است.
- توضیح "چرایی" وقوع ناهنجاری با نگاه به بستر داده.
- رتبه‌بندی ناهنجاری‌ها از نظر اهمیت استراتژیک.

4️⃣ تحلیل الگوهای پنهان و کیفیت داده 🧠
- بررسی اینکه آیا ناهنجاری‌ها نشانه خطای ثبت داده هستند یا یک فرصت/تهدید واقعی در سیستم.
- تحلیل توزیع و چگالی داده‌ها در نقاط بحرانی.

5️⃣ پیشنهادها و راهکارهای مدیریتی 📈
- ارائه حداقل ۳ راهکار عملیاتی برای مدیریت این ناهنجاری‌ها.
- توصیه برای بهبود کیفیت داده‌ها در آینده.
- برآورد سطح ریسک کلی بر اساس تحلیل تمام ابعاد فایل.

------------------------------------------------------------
# ❌ STRICT RULES
- از ابداع داده‌ها خودداری کنید.
- فقط بر اساس فایل واقعی تحلیل کنید.
- از کلمات فنی مثل "DataFrame" یا "Library" استفاده نکنید.
- پاسخ باید بسیار خوانا، روان و با استفاده از ایموجی‌های مناسب باشد.
"""
    return prompt
